# Select numeric release tags only; branches and prereleases are not stable releases.
stable_git_tag() {
    local tag
    tag="$(git_ls_remote --tags --refs "$1" | sed -nE 's#.*refs/tags/(v?[0-9]+\.[0-9]+(\.[0-9]+)?)$#\1#p' | sort -V | tail -n 1)" || return 1
    if [ -z "$tag" ]; then
        warning "cannot discover a stable release tag for $1"
        return 1
    fi
    printf '%s\n' "$tag"
}

stable_git_hash() {
    local tag hash
    tag="${2:-$(stable_git_tag "$1")}" || return 1
    # Dereference annotated tags to the source commit.
    hash="$(git_ls_remote "$1" "refs/tags/$tag" "refs/tags/$tag^{}" | awk '
        /\^\{\}$/ { peeled = $1 }
        { hash = $1 }
        END { if (peeled != "") print peeled; else print hash }
    ')" || return 1
    [ -n "$hash" ] || { warning "cannot resolve release tag $tag for $1"; return 1; }
    printf '%s\n' "$hash"
}

